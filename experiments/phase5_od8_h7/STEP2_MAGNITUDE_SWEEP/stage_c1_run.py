"""Stage C1 runner - magnitude sweep for L1-vs-gate quadrants.

Executes the design in ``preregistration.md``. For each of four
parameterised faults, at five magnitudes each, drives 30 seeds with the
Stage A logger attached. Clean baseline is not re-run: Stage A's
``raw_results/clean_<seed>.jsonl`` files are seed-deterministic and cover
this sweep's clean arm at zero additional wall cost.

Do not edit this file after 22 September 2026 without a matching
amendment.md; the pre-registration binds to the code as committed.

Usage
-----

Dev sweep (primary; ~70 min)::

    uv run python experiments/phase5_od8_h7/STEP2_MAGNITUDE_SWEEP/stage_c1_run.py

Held-out sweep (Stage D, after C2/C3 land)::

    uv run python experiments/phase5_od8_h7/STEP2_MAGNITUDE_SWEEP/stage_c1_run.py \\
        --base-seed 20261201 \\
        --out experiments/phase5_od8_h7/STEP2_MAGNITUDE_SWEEP/raw_results_heldout
"""

from __future__ import annotations

import argparse
import csv
import inspect
import json
import subprocess
import sys
import time
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parents[3]))

from astra.layers.l4_proposer.learned import LearnedPolicy  # noqa: E402
from benchmarks.detectors import DETECTORS, evaluate  # noqa: E402
from benchmarks.e18r3c_sustained import _injector_full, _sensing_full  # noqa: E402
from benchmarks.e18_evaluate import SEVERITIES  # noqa: E402
from benchmarks.mechanism_logger import TickLogger  # noqa: E402
from training.closed_loop import drive_closed_loop  # noqa: E402

FROZEN_V3_P1 = 3.7024
DEV_BASE_SEED = 20260731
HELD_OUT_BASE_SEED = 20261201
N_SEEDS = 30
TICKS = 3400
POLICY_NAME = "P1"
CKPT = "synthetic"

# Only parameterised faults are in scope for this sweep. Dropout and stuck-at
# take no magnitude and are covered by Stage A.
FAULTS: tuple[str, ...] = (
    "position_bias",
    "position_drift",
    "speed_bias",
    "lateral_noise",
)


def _magnitudes(fault: str) -> list[tuple[str, float]]:
    """Return the five (label, magnitude) points for a fault.

    ``low``, ``medium``, ``high`` are the committed points from ``SEVERITIES``.
    ``subthreshold`` = 0.1x low is a deliberately small point to expose L1's
    detection boundary; ``mid_low`` = 0.5x medium fills the gap between low
    and medium.
    """
    levels = SEVERITIES[fault]["levels"]
    low = float(levels["low"])
    medium = float(levels["medium"])
    high = float(levels["high"])
    return [
        ("subthreshold", 0.1 * low),
        ("low", low),
        ("mid_low", 0.5 * medium),
        ("medium", medium),
        ("high", high),
    ]


def _integrity_checks() -> None:
    """Same guards as Stage A; a broken invariant here would silently
    contaminate 600 runs the same way it would 210."""
    signature = inspect.signature(drive_closed_loop)
    default = signature.parameters["demo_speed_assist"].default
    if default is not False:
        raise RuntimeError(
            f"drive_closed_loop.demo_speed_assist default is {default!r}, "
            f"not False. Stage 0's invariant is broken; sweep must not proceed."
        )
    dirty = subprocess.run(
        ["git", "status", "--porcelain"],
        capture_output=True,
        text=True,
        check=True,
    ).stdout.strip()
    tracked_changes = [
        line for line in dirty.splitlines() if not line.startswith("??")
    ]
    if tracked_changes:
        raise RuntimeError(
            "Git working tree has staged or modified files:\n  "
            + "\n  ".join(tracked_changes)
            + "\n\nCommit or stash them before running the Stage C1 sweep."
        )


L1_DETECTOR_NAME = "health"
"""E21's L1 detector (see benchmarks.detectors.DETECTORS). Kept as a constant
so a rename catches this file at import time, not silently at analysis time."""


def _run_one(
    *,
    policy: Any,
    fault: str,
    magnitude_label: str,
    magnitude: float,
    seed: int,
    ticks: int,
    output_path: Path,
    header_common: dict[str, Any],
) -> tuple[int, dict[str, Any]]:
    """Drive one faulted run at (fault, magnitude, seed).

    Returns (n_ticks_written, run_summary). run_summary carries L1's
    detection result on this run so the analyser does not need to re-drive
    the pipeline or re-invoke the detectors.
    """
    header = {
        **header_common,
        "seed": seed,
        "fault": fault,
        "arm": "faulted",
        "magnitude_label": magnitude_label,
        "magnitude_value": magnitude,
        "fault_onset_tick": 200,
    }
    logger = TickLogger(output_path=output_path, header=header)
    records: list[Any] = []

    def _observe(sample: Any) -> None:
        logger(sample)
        records.append(sample.record)

    injector = _injector_full(fault, magnitude, seed, ticks)
    sensing = _sensing_full(fault, magnitude, seed, ticks, active=True)
    try:
        drive_closed_loop(
            policy=policy,
            ticks=ticks,
            seed=seed,
            observer=_observe,
            fault=injector,
            redundant=sensing,
        )
    finally:
        n = logger.close()

    # Score every detector on this run and pull out L1's answer. Reused
    # verbatim from E21's pipeline; nothing here recomputes a detector.
    truth = [index >= 200 for index in range(len(records))]
    detections = evaluate(records, fault_active=truth, opened_at=200)
    l1 = next((d for d in detections if d.detector == L1_DETECTOR_NAME), None)
    return n, {
        "fault": fault,
        "magnitude_label": magnitude_label,
        "magnitude_value": magnitude,
        "seed": seed,
        "l1_detected": bool(l1 is not None and l1.fired_at is not None and l1.fired_at >= 200),
        "l1_first_fire_tick": None if l1 is None else l1.fired_at,
        "l1_latency_ticks": None if l1 is None else l1.latency_ticks,
        "l1_false_alarm": bool(l1 is not None and l1.false_alarm),
        "n_ticks": n,
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--base-seed", type=int, default=DEV_BASE_SEED)
    parser.add_argument("--seeds", type=int, default=N_SEEDS)
    parser.add_argument("--ticks", type=int, default=TICKS)
    parser.add_argument(
        "--out",
        type=Path,
        default=Path("experiments/phase5_od8_h7/STEP2_MAGNITUDE_SWEEP/raw_results"),
    )
    parser.add_argument("--faults", nargs="+", default=list(FAULTS))
    args = parser.parse_args()

    _integrity_checks()

    args.out.mkdir(parents=True, exist_ok=True)
    manifest_path = args.out / "manifest.csv"
    git_sha = subprocess.check_output(["git", "rev-parse", "HEAD"], text=True).strip()
    policy = LearnedPolicy.load(Path(f"var/policy/{CKPT}.pt"))
    header_common = {
        "experiment_id": "stage_c1_magnitude_sweep",
        "policy": POLICY_NAME,
        "policy_ckpt": CKPT,
        "threshold": FROZEN_V3_P1,
        "ticks": args.ticks,
        "git_sha": git_sha,
        "base_seed": args.base_seed,
    }

    if args.base_seed not in {DEV_BASE_SEED, HELD_OUT_BASE_SEED}:
        print(
            f"warning: base-seed {args.base_seed} is not a pre-registered set. "
            f"Proceeding anyway; this had better be a smoke test.",
            file=sys.stderr,
        )

    unknown = [f for f in args.faults if f not in FAULTS]
    if unknown:
        raise RuntimeError(
            f"unknown or unparameterised fault(s) in --faults: {unknown!r}. "
            f"Stage C1 is scoped to {list(FAULTS)!r}."
        )

    t0 = time.time()
    total = len(args.faults) * 5 * args.seeds
    completed = 0
    per_run_summaries: list[dict[str, Any]] = []

    with manifest_path.open("w", encoding="utf-8", newline="") as mf:
        writer = csv.DictWriter(
            mf,
            fieldnames=[
                "fault", "magnitude_label", "magnitude_value", "seed",
                "path", "ticks_written", "l1_detected", "l1_first_fire_tick",
                "wall_secs",
            ],
        )
        writer.writeheader()

        for fault in args.faults:
            for mag_label, mag_value in _magnitudes(fault):
                for seed_offset in range(args.seeds):
                    seed = args.base_seed + seed_offset
                    filename = f"{fault}_{mag_label}_{seed}.jsonl"
                    output_path = args.out / filename
                    run_start = time.time()
                    ticks_written, run_summary = _run_one(
                        policy=policy,
                        fault=fault,
                        magnitude_label=mag_label,
                        magnitude=mag_value,
                        seed=seed,
                        ticks=args.ticks,
                        output_path=output_path,
                        header_common=header_common,
                    )
                    wall_secs = time.time() - run_start
                    per_run_summaries.append(run_summary)
                    row = {
                        "fault": fault,
                        "magnitude_label": mag_label,
                        "magnitude_value": mag_value,
                        "seed": seed,
                        "path": str(output_path.relative_to(args.out.parent.parent.parent)),
                        "ticks_written": ticks_written,
                        "l1_detected": int(run_summary["l1_detected"]),
                        "l1_first_fire_tick": run_summary["l1_first_fire_tick"],
                        "wall_secs": round(wall_secs, 2),
                    }
                    writer.writerow(row)
                    mf.flush()
                    completed += 1
                    l1_mark = "L1+" if run_summary["l1_detected"] else "L1-"
                    print(
                        f"  [{completed:>3}/{total}] {fault:<16} "
                        f"{mag_label:<12}={mag_value:>7.3f} seed={seed} "
                        f"{l1_mark} ({wall_secs:.1f}s)  "
                        f"elapsed {int(time.time() - t0)}s",
                        flush=True,
                    )

    # Per-run detector summary goes with the manifest so the analyser does
    # not need to walk raw JSONL to recover L1's answer.
    (args.out / "detector_summary.json").write_text(
        json.dumps(per_run_summaries, indent=1), encoding="utf-8",
    )

    summary_path = args.out / "run_summary.json"
    summary_path.write_text(
        json.dumps({
            "git_sha": git_sha,
            "base_seed": args.base_seed,
            "n_seeds": args.seeds,
            "ticks": args.ticks,
            "threshold": FROZEN_V3_P1,
            "n_runs": completed,
            "wall_secs_total": round(time.time() - t0, 2),
            "faults": list(args.faults),
        }, indent=2),
        encoding="utf-8",
    )
    print(f"\ndone. {completed} runs -> {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
