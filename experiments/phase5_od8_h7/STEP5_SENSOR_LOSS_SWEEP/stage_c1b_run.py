"""Stage C1b runner - sensor-loss magnitude sweep for the shift branch.

Executes the design in ``preregistration.md``. 4 probabilities x 30 dev
seeds = 120 faulted runs, each attaching the Stage A per-tick logger AND
running the E21 detectors to capture L1's per-run answer. Clean baseline
reused from Stage A (seed-deterministic; no re-execution).

Do not edit this file after 24 September 2026 without a matching
amendment.md; the pre-registration binds to the code as committed.
"""

from __future__ import annotations

import argparse
import csv
import inspect
import json
import subprocess
import sys
import time
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parents[3]))

from astra.layers.l4_proposer.learned import LearnedPolicy  # noqa: E402
from benchmarks.detectors import evaluate  # noqa: E402
from benchmarks.discriminability import CHANNEL_SIGMAS  # noqa: E402
from benchmarks.e18r3c_sustained import _sensing_full  # noqa: E402
from benchmarks.graded_dropout import graded_dropout_injector  # noqa: E402
from benchmarks.mechanism_logger import TickLogger  # noqa: E402
from training.closed_loop import drive_closed_loop  # noqa: E402

FROZEN_V3_P1 = 3.7024
DEV_BASE_SEED = 20260731
HELD_OUT_BASE_SEED = 20261201
N_SEEDS = 30
TICKS = 3400
FAULT_ONSET = 200
POLICY_NAME = "P1"
CKPT = "synthetic"
L1_DETECTOR_NAME = "health"

# The four probabilities. p = 1.0 reproduces R3c / Stage A / E21 baseline.
PROBABILITIES: tuple[tuple[str, float], ...] = (
    ("p025", 0.25),
    ("p050", 0.50),
    ("p075", 0.75),
    ("p100", 1.00),
)


def _integrity_checks() -> None:
    """Same guards as Stage A / C1: broken invariant here would silently
    contaminate 120 runs the same way it would 210 or 600."""
    signature = inspect.signature(drive_closed_loop)
    default = signature.parameters["demo_speed_assist"].default
    if default is not False:
        raise RuntimeError(
            f"drive_closed_loop.demo_speed_assist default is {default!r}, "
            f"not False. Stage 0's invariant is broken; sweep must not proceed."
        )
    dirty = subprocess.run(
        ["git", "status", "--porcelain"],
        capture_output=True,
        text=True,
        check=True,
    ).stdout.strip()
    tracked_changes = [
        line for line in dirty.splitlines() if not line.startswith("??")
    ]
    if tracked_changes:
        raise RuntimeError(
            "Git working tree has staged or modified files:\n  "
            + "\n  ".join(tracked_changes)
            + "\n\nCommit or stash them before running the Stage C1b sweep."
        )


def _run_one(
    *,
    policy: Any,
    probability_label: str,
    probability: float,
    seed: int,
    ticks: int,
    output_path: Path,
    header_common: dict[str, Any],
) -> tuple[int, dict[str, Any]]:
    """Drive one run with graded IMU dropout at ``probability``."""
    header = {
        **header_common,
        "seed": seed,
        "fault": "imu_dropout",
        "arm": "faulted",
        "magnitude_label": probability_label,
        "magnitude_value": probability,
        "fault_onset_tick": FAULT_ONSET,
    }
    logger = TickLogger(output_path=output_path, header=header)
    records: list[Any] = []

    def _observe(sample: Any) -> None:
        logger(sample)
        records.append(sample.record)

    injector = graded_dropout_injector(
        first_tick=FAULT_ONSET,
        last_tick=ticks - 1,
        probability=probability,
        seed=seed,
        sigmas=CHANNEL_SIGMAS,
    )
    # No sensing spec: this is an IMU dropout, not a position bias/drift.
    sensing = _sensing_full("imu_dropout", None, seed, ticks, active=False)
    try:
        drive_closed_loop(
            policy=policy,
            ticks=ticks,
            seed=seed,
            observer=_observe,
            fault=injector,
            redundant=sensing,
        )
    finally:
        n = logger.close()

    truth = [i >= FAULT_ONSET for i in range(len(records))]
    detections = evaluate(records, fault_active=truth, opened_at=FAULT_ONSET)
    l1 = next((d for d in detections if d.detector == L1_DETECTOR_NAME), None)

    # Count achieved dropouts for provenance -- the injector reports
    # per-spec tallies, so summing gives the number of ticks actually
    # dropped.
    achieved = sum(1 for t in range(FAULT_ONSET, ticks) if injector.drops_reading(t))
    return n, {
        "fault": "imu_dropout",
        "magnitude_label": probability_label,
        "magnitude_value": probability,
        "seed": seed,
        "l1_detected": bool(l1 is not None and l1.fired_at is not None and l1.fired_at >= FAULT_ONSET),
        "l1_first_fire_tick": None if l1 is None else l1.fired_at,
        "l1_latency_ticks": None if l1 is None else l1.latency_ticks,
        "l1_false_alarm": bool(l1 is not None and l1.false_alarm),
        "n_ticks": n,
        "achieved_dropouts": achieved,
        "achieved_dropout_fraction": achieved / (ticks - FAULT_ONSET),
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--base-seed", type=int, default=DEV_BASE_SEED)
    parser.add_argument("--seeds", type=int, default=N_SEEDS)
    parser.add_argument("--ticks", type=int, default=TICKS)
    parser.add_argument(
        "--out",
        type=Path,
        default=Path("experiments/phase5_od8_h7/STEP5_SENSOR_LOSS_SWEEP/raw_results"),
    )
    args = parser.parse_args()

    _integrity_checks()

    args.out.mkdir(parents=True, exist_ok=True)
    manifest_path = args.out / "manifest.csv"
    git_sha = subprocess.check_output(["git", "rev-parse", "HEAD"], text=True).strip()
    policy = LearnedPolicy.load(Path(f"var/policy/{CKPT}.pt"))
    header_common = {
        "experiment_id": "stage_c1b_sensor_loss",
        "policy": POLICY_NAME,
        "policy_ckpt": CKPT,
        "threshold": FROZEN_V3_P1,
        "ticks": args.ticks,
        "git_sha": git_sha,
        "base_seed": args.base_seed,
    }

    if args.base_seed not in {DEV_BASE_SEED, HELD_OUT_BASE_SEED}:
        print(
            f"warning: base-seed {args.base_seed} is not a pre-registered set. "
            f"Proceeding anyway; this had better be a smoke test.",
            file=sys.stderr,
        )

    t0 = time.time()
    total = len(PROBABILITIES) * args.seeds
    completed = 0
    per_run_summaries: list[dict[str, Any]] = []

    with manifest_path.open("w", encoding="utf-8", newline="") as mf:
        writer = csv.DictWriter(
            mf,
            fieldnames=[
                "fault", "magnitude_label", "magnitude_value", "seed",
                "path", "ticks_written", "l1_detected", "l1_first_fire_tick",
                "achieved_dropout_fraction", "wall_secs",
            ],
        )
        writer.writeheader()

        for prob_label, prob_value in PROBABILITIES:
            for seed_offset in range(args.seeds):
                seed = args.base_seed + seed_offset
                filename = f"imu_dropout_{prob_label}_{seed}.jsonl"
                output_path = args.out / filename
                run_start = time.time()
                ticks_written, run_summary = _run_one(
                    policy=policy,
                    probability_label=prob_label,
                    probability=prob_value,
                    seed=seed,
                    ticks=args.ticks,
                    output_path=output_path,
                    header_common=header_common,
                )
                wall_secs = time.time() - run_start
                per_run_summaries.append(run_summary)
                row = {
                    "fault": "imu_dropout",
                    "magnitude_label": prob_label,
                    "magnitude_value": prob_value,
                    "seed": seed,
                    "path": str(output_path.relative_to(args.out.parent.parent.parent)),
                    "ticks_written": ticks_written,
                    "l1_detected": int(run_summary["l1_detected"]),
                    "l1_first_fire_tick": run_summary["l1_first_fire_tick"],
                    "achieved_dropout_fraction": round(run_summary["achieved_dropout_fraction"], 4),
                    "wall_secs": round(wall_secs, 2),
                }
                writer.writerow(row)
                mf.flush()
                completed += 1
                l1_mark = "L1+" if run_summary["l1_detected"] else "L1-"
                print(
                    f"  [{completed:>3}/{total}] imu_dropout {prob_label:<6} p={prob_value:.2f} "
                    f"seed={seed} achieved={run_summary['achieved_dropout_fraction']:.2f} "
                    f"{l1_mark} ({wall_secs:.1f}s)  elapsed {int(time.time() - t0)}s",
                    flush=True,
                )

    (args.out / "detector_summary.json").write_text(
        json.dumps(per_run_summaries, indent=1), encoding="utf-8",
    )
    (args.out / "run_summary.json").write_text(
        json.dumps({
            "git_sha": git_sha,
            "base_seed": args.base_seed,
            "n_seeds": args.seeds,
            "ticks": args.ticks,
            "threshold": FROZEN_V3_P1,
            "n_runs": completed,
            "wall_secs_total": round(time.time() - t0, 2),
            "probabilities": [{"label": lbl, "value": val} for lbl, val in PROBABILITIES],
        }, indent=2),
        encoding="utf-8",
    )
    print(f"\ndone. {completed} runs -> {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
