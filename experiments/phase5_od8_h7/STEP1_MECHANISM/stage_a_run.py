"""Stage A runner - executes the pre-registered mechanism sweep.

Two arms per fault, per seed:
  - faulted: sustained fault active from tick 200 to the end of the run.
  - clean:   same seed, no fault; the paired baseline for §4's ratios.

Produces one JSONL file per run (60 runs per fault × 6 faults per base-seed set),
plus a manifest CSV mapping every run to its filepath. Reads only the frozen v3
threshold from the pre-registered constant; recomputes nothing.

Do not edit this file after 22 September 2026 without a matching amendment.md;
the pre-registration binds to the code exactly as committed.

Usage
-----
Dev sweep (the primary analysis)::

    uv run python experiments/phase5_od8_h7/STEP1_MECHANISM/stage_a_run.py

Held-out sweep (runs once, after final_decision.md lands on the dev data)::

    uv run python experiments/phase5_od8_h7/STEP1_MECHANISM/stage_a_run.py \\
        --base-seed 20261201 \\
        --out experiments/phase5_od8_h7/STEP1_MECHANISM/raw_results_heldout
"""

from __future__ import annotations

import argparse
import csv
import inspect
import json
import subprocess
import sys
import time
from pathlib import Path
from typing import Any

# The runner is invoked as a top-level script (`python .../stage_a_run.py ...`),
# not as a module, so the repo root is not automatically on ``sys.path``. Match
# the deesc_probe.py pattern rather than requiring `-m`, which is what the
# handoff §1.4 quick-run example uses too.
sys.path.insert(0, str(Path(__file__).resolve().parents[3]))

from astra.layers.l4_proposer.learned import LearnedPolicy  # noqa: E402
from benchmarks.discriminability import CHANNEL_SIGMAS, _FAULT_FIRST
from benchmarks.e18_evaluate import SEVERITIES
from benchmarks.e18r3c_sustained import _injector_full, _sensing_full
from benchmarks.mechanism_logger import TickLogger
from training.closed_loop import drive_closed_loop

# Frozen constants (pre-reg §2). No override flag on purpose: a threshold is
# not something to pass on the command line for a pre-registered study.
FROZEN_V3_P1 = 3.7024
DEV_BASE_SEED = 20260731
HELD_OUT_BASE_SEED = 20261201
N_SEEDS = 30
TICKS = 3400
FAULT_ONSET = _FAULT_FIRST  # 200, matches R3b/R3c/E21
LEVEL = "medium"
POLICY_NAME = "P1"
CKPT = "synthetic"

# The six faults R3c ran. If §10 of the pre-reg agrees to trim the set, the
# amendment.md records the decision and this constant changes there.
FAULTS: tuple[str, ...] = (
    "imu_dropout",
    "imu_bias",
    "lateral_noise",
    "position_bias",
    "position_drift",
    "speed_bias",
)


def _integrity_checks() -> None:
    """Fail loudly before the first run rather than after the last one.

    - The default of ``demo_speed_assist`` on ``drive_closed_loop`` must be
      ``False`` (Stage 0). Every run below leaves this argument at its
      default; a regression that flipped the default would silently
      contaminate the sweep.
    - Git working tree must be clean, so the pre-reg's "code committed before
      the first tick" story is honest. An amendment during a run makes the
      provenance ambiguous.
    """
    signature = inspect.signature(drive_closed_loop)
    default = signature.parameters["demo_speed_assist"].default
    if default is not False:
        raise RuntimeError(
            f"drive_closed_loop.demo_speed_assist default is {default!r}, "
            f"not False. Stage 0's invariant is broken; the sweep must not "
            f"proceed until it is restored."
        )
    dirty = subprocess.run(
        ["git", "status", "--porcelain"],
        capture_output=True,
        text=True,
        check=True,
    ).stdout.strip()
    if dirty:
        # Personal-untracked files (letters, unrelated markdown) are OK. Only
        # tracked-modified or staged changes count as a live edit that would
        # muddy the provenance.
        tracked_changes = [
            line
            for line in dirty.splitlines()
            if not line.startswith("??")
        ]
        if tracked_changes:
            raise RuntimeError(
                "Git working tree has staged or modified files:\n  "
                + "\n  ".join(tracked_changes)
                + "\n\nCommit or stash them before running the Stage A sweep."
            )


def _run_one(
    *,
    policy: Any,
    fault: str | None,
    severity: float | None,
    seed: int,
    ticks: int,
    output_path: Path,
    header_common: dict[str, Any],
) -> int:
    """Drive one closed-loop run, writing every tick to ``output_path``."""
    header = {
        **header_common,
        "seed": seed,
        "fault": fault if fault is not None else "clean",
        "arm": "faulted" if fault is not None else "clean",
        "fault_onset_tick": FAULT_ONSET if fault is not None else None,
        "severity_level": LEVEL if fault is not None else None,
        "severity_value": severity if fault is not None else None,
    }
    logger = TickLogger(output_path=output_path, header=header)
    injector = _injector_full(fault, severity, seed, ticks) if fault is not None else None
    sensing = _sensing_full(fault, severity, seed, ticks, active=(fault is not None))
    try:
        drive_closed_loop(
            policy=policy,
            ticks=ticks,
            seed=seed,
            observer=logger,
            fault=injector,
            redundant=sensing,
        )
    finally:
        n = logger.close()
    return n


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Stage A runner. Runs the pre-registered dev sweep by "
        "default; pass --base-seed 20261201 for the held-out sweep.",
    )
    parser.add_argument("--base-seed", type=int, default=DEV_BASE_SEED)
    parser.add_argument("--seeds", type=int, default=N_SEEDS)
    parser.add_argument("--ticks", type=int, default=TICKS)
    parser.add_argument(
        "--out",
        type=Path,
        default=Path("experiments/phase5_od8_h7/STEP1_MECHANISM/raw_results"),
    )
    parser.add_argument(
        "--faults",
        nargs="+",
        default=list(FAULTS),
        help="For smoke tests only; the primary run must not restrict this.",
    )
    parser.add_argument(
        "--arms",
        choices=("both", "faulted", "clean"),
        default="both",
    )
    args = parser.parse_args()

    _integrity_checks()

    args.out.mkdir(parents=True, exist_ok=True)
    manifest_path = args.out / "manifest.csv"
    git_sha = subprocess.check_output(["git", "rev-parse", "HEAD"], text=True).strip()
    policy = LearnedPolicy.load(Path(f"var/policy/{CKPT}.pt"))
    header_common = {
        "experiment_id": "stage_a_mechanism",
        "policy": POLICY_NAME,
        "policy_ckpt": CKPT,
        "threshold": FROZEN_V3_P1,
        "ticks": args.ticks,
        "git_sha": git_sha,
        "base_seed": args.base_seed,
    }

    # Warn (not fail) if base seed does not match either pre-registered set --
    # the runner is only expected to be invoked in two configurations, and
    # anything else is either a smoke test or a mistake.
    if args.base_seed not in {DEV_BASE_SEED, HELD_OUT_BASE_SEED}:
        print(
            f"warning: base-seed {args.base_seed} is not a pre-registered "
            f"seed set ({DEV_BASE_SEED} dev, {HELD_OUT_BASE_SEED} held-out). "
            f"Proceeding anyway; this had better be a smoke test.",
            file=sys.stderr,
        )

    severities = {
        fault: SEVERITIES[fault]["levels"].get(LEVEL)
        for fault in args.faults
        if fault in SEVERITIES and LEVEL in SEVERITIES[fault]["levels"]
    }
    for fault in args.faults:
        if fault not in severities:
            print(f"warning: fault {fault!r} has no {LEVEL} severity; skipping.", file=sys.stderr)

    manifest_rows: list[dict[str, Any]] = []
    t0 = time.time()
    total_runs = len(severities) * args.seeds * (2 if args.arms == "both" else 1)
    completed = 0

    with manifest_path.open("w", encoding="utf-8", newline="") as manifest_handle:
        writer = csv.DictWriter(
            manifest_handle,
            fieldnames=[
                "fault",
                "arm",
                "seed",
                "path",
                "ticks_written",
                "wall_secs",
            ],
        )
        writer.writeheader()

        arms = ("faulted", "clean") if args.arms == "both" else (args.arms,)
        for fault_name, severity in severities.items():
            for seed_offset in range(args.seeds):
                seed = args.base_seed + seed_offset
                for arm in arms:
                    fault_or_none = fault_name if arm == "faulted" else None
                    filename = f"{fault_name}_{arm}_{seed}.jsonl"
                    output_path = args.out / filename
                    run_start = time.time()
                    ticks_written = _run_one(
                        policy=policy,
                        fault=fault_or_none,
                        severity=severity,
                        seed=seed,
                        ticks=args.ticks,
                        output_path=output_path,
                        header_common=header_common,
                    )
                    wall_secs = time.time() - run_start
                    row = {
                        "fault": fault_name,
                        "arm": arm,
                        "seed": seed,
                        "path": str(output_path.relative_to(args.out.parent.parent.parent)),
                        "ticks_written": ticks_written,
                        "wall_secs": round(wall_secs, 2),
                    }
                    writer.writerow(row)
                    manifest_handle.flush()
                    manifest_rows.append(row)
                    completed += 1
                    print(
                        f"  [{completed:>3}/{total_runs}] {fault_name:<16} "
                        f"{arm:<8} seed={seed} ticks={ticks_written} "
                        f"({wall_secs:.1f}s)  elapsed {int(time.time() - t0)}s",
                        flush=True,
                    )

    summary_path = args.out / "run_summary.json"
    summary_path.write_text(
        json.dumps(
            {
                "git_sha": git_sha,
                "base_seed": args.base_seed,
                "n_seeds": args.seeds,
                "ticks": args.ticks,
                "threshold": FROZEN_V3_P1,
                "n_runs": len(manifest_rows),
                "wall_secs_total": round(time.time() - t0, 2),
                "faults": list(severities.keys()),
                "arms": list(arms),
            },
            indent=2,
        ),
        encoding="utf-8",
    )
    print(f"\ndone. {len(manifest_rows)} runs -> {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
